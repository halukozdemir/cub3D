#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*str;
	size_t	first;
	size_t	last;

	if (!s1 || !set)
		return (NULL);
	first = 0;
	last = ft_strlen(s1);
	while (s1[first] && ft_strchr(set, s1[first]))
		first++;
	while (last > first && ft_strchr(set, s1[last - 1]))
		last--;
	str = (char *)malloc(sizeof(char) * (last - first + 1));
	if (!str)
		return (NULL);
	ft_strlcpy (str, &s1[first], last - first + 1);
	return (str);
}
